// Copies the line icons the site uses from lucide (ISC licence) into src/components/ui/icon-data.ts,
// so the rendered SVGs carry no library class names. Run after adding an icon: node scripts/vendor-icons.mjs
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { join } from "node:path";

const names = [
  "ArrowRight",
  "ArrowUpRight",
  "ChevronDown",
  "CircleAlert",
  "CircleCheck",
  "Clock",
  "LoaderCircle",
  "Mail",
  "MapPin",
  "Menu",
  "MessageCircle",
  "Phone",
  "Plus",
  "X",
  "AppWindow",
  "Bot",
  "ChartColumn",
  "ChartPie",
  "Cloud",
  "Code",
  "Compass",
  "Database",
  "FileSearch",
  "Gauge",
  "GitBranch",
  "Globe",
  "LayoutDashboard",
  "Lightbulb",
  "MousePointerClick",
  "Newspaper",
  "PenTool",
  "Plug",
  "Rocket",
  "ScanSearch",
  "Search",
  "ShieldCheck",
  "ShoppingCart",
  "Smartphone",
  "Sparkles",
  "Target",
  "TestTube",
  "TrendingUp",
  "Workflow",
  "Wrench",
];
const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const dir = join(process.cwd(), "node_modules/lucide-react/dist/esm/icons");
const out = {};
for (const n of names) {
  const mod = await import(pathToFileURL(join(dir, `${kebab(n)}.mjs`)).href);
  out[n] = mod.__iconData.node.map(([tag, attrs]) => {
    const rest = { ...attrs };
    delete rest.key;
    return [tag, rest];
  });
}
const body = `// Generated by scripts/vendor-icons.mjs from lucide (https://lucide.dev, ISC licence). Do not edit.
export const iconData = ${JSON.stringify(out, null, 2)} as const;

export type IconKey = keyof typeof iconData;
`;
writeFileSync("src/components/ui/icon-data.ts", body);
console.log(`Wrote ${names.length} icons`);
